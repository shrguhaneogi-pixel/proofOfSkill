/**
 * Byte-level constants for the onchain `proof_of_skill` program.
 *
 * `anchor build` is blocked on this host (see docs/living-notes.md → Blockers), so no IDL
 * exists. These values are the IDL's substitutes and must equal the Rust source exactly:
 * discriminators are `sha256("global:<instruction>")` / `sha256("account:<Struct>")`
 * truncated to 8 bytes, and the account sizes are `8 + InitSpace`. `codecs.test.ts` recomputes
 * every discriminator from its Anchor preimage so a typo cannot silently survive.
 */

import { CHALLENGE_IDS, type ChallengeId } from "../challenges/types";
import { hexToBytes } from "../hashing/evidence-hash";

function utf8Bytes(value: string): Uint8Array {
  return new TextEncoder().encode(value);
}

export const DISCRIMINATOR_LENGTH = 8;
export const PUBLIC_KEY_LENGTH = 32;
export const EVIDENCE_HASH_LENGTH = 32;

