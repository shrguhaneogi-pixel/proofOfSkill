export const PASS_THRESHOLD = 70;

const CHALLENGE_ID_SET: ReadonlySet<number> = new Set<number>(CHALLENGE_IDS);

/** Narrows an untrusted number to the onchain `MIN_CHALLENGE_ID..=MAX_CHALLENGE_ID` range. */
export function isChallengeId(value: number): value is ChallengeId {
  return Number.isInteger(value) && CHALLENGE_ID_SET.has(value);
}

